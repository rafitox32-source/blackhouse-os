-- Migración 006: Módulo POS de Ventas para la Vendedora (app Android enlazada a la web)
-- Motor: PostgreSQL (Supabase, proyecto flfhpffslhjcuvhxsnjz)
--
-- Objetivo funcional (pedido del dueño):
--   1) La vendedora vende productos que SÍ están en inventario -> descuenta el stock real.
--   2) La vendedora puede vender un producto que NO tiene en inventario (ej. un "chip"):
--      ese producto NO toca el stock ni crea un producto de inventario. Se guarda aparte en
--      productos_venta_libre para que la PRÓXIMA vez ya aparezca disponible para vender, con el
--      precio que ella usó, sin haber agregado stock.
--   3) Al final del día puede hacer "cierre de caja" y obtener el total de las ventas del día.
--
-- Arquitectura de seguridad (importante):
--   La web/APK NO usa la service_role key (esa solo la usa el escritorio en main.js). La web usa
--   la ANON key pública y SOLO puede llamar a las funciones pos_* de abajo. Todas son
--   SECURITY DEFINER y resuelven la empresa a partir de un TOKEN de sesión guardado en
--   pos_sesiones: el cliente nunca envía su empresa_id, así que una vendedora jamás puede leer ni
--   escribir datos de otra empresa. Las tablas tienen RLS activado y SIN permisos directos para
--   anon; el único camino es a través de estas funciones.
--
-- Verificación de esquema hecha antes de escribir (mismo patrón que 002/003/005):
--   - productos: columnas reales nombre, precio, stock, sku, categoria, empresa_id (numérico).
--     OJO: la migración 001 (vw_productos_pos) usaba stock_disponible/precio_venta, que NO existen.
--     Esta migración usa las columnas reales y crea una vista corregida al final.
--   - usuarios: usuario, password (bcrypt $2b$ o texto plano heredado), rol, estado, empresa_id,
--     nombre_completo, nickname, id.
--   - empresas: id, fecha_de_vencimiento.
--   - movimientos_stock: empresa_id text, sku text, cantidad integer, nota nullable, creado_en.
--
-- NO APLICADA POR EL AGENTE: solo se prepara el archivo. Aplícala desde el SQL Editor de Supabase.

BEGIN;

-- pgcrypto: para verificar contraseñas bcrypt (crypt) y generar tokens (gen_random_bytes).
