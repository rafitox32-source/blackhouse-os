-- Productos que la vendedora vende SIN tenerlos en inventario. NUNCA tocan productos.stock.
-- Se "recuerdan" por empresa para que reaparezcan en la próxima venta.
CREATE TABLE IF NOT EXISTS public.productos_venta_libre (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     bigint  NOT NULL,
    nombre         text    NOT NULL,
    precio         numeric NOT NULL DEFAULT 0,
    veces_vendido  integer NOT NULL DEFAULT 0,
    activo         boolean NOT NULL DEFAULT true,
    creado_en      timestamptz NOT NULL DEFAULT now(),
    actualizado_en timestamptz NOT NULL DEFAULT now()
);
-- Un mismo nombre no se duplica por empresa (case-insensitive). Este índice también es el que
-- usa el ON CONFLICT de pos_registrar_venta.
CREATE UNIQUE INDEX IF NOT EXISTS uq_venta_libre_empresa_nombre
    ON public.productos_venta_libre (empresa_id, lower(nombre));

-- Sesiones del POS: el token que la web guarda tras el login. La empresa se resuelve desde acá.
CREATE TABLE IF NOT EXISTS public.pos_sesiones (
    token       text PRIMARY KEY,
    usuario_id  text,          -- text para servir tanto si usuarios.id es entero como UUID
    empresa_id  bigint NOT NULL,
    rol         text,
    usuario     text,
    nombre      text,
    creado_en   timestamptz NOT NULL DEFAULT now(),
    expira_en   timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pos_sesiones_expira ON public.pos_sesiones(expira_en);

-- Cabecera de cada venta (ticket).
CREATE TABLE IF NOT EXISTS public.ventas_pos (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       bigint  NOT NULL,
    vendedor_id      text,
    vendedor_usuario text,
    total            numeric NOT NULL DEFAULT 0,
    medio_pago       text    NOT NULL DEFAULT 'efectivo',
    cierre_id        bigint,       -- se completa cuando la venta entra en un cierre de caja
    creado_en        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ventas_pos_empresa_fecha ON public.ventas_pos(empresa_id, creado_en);

-- Líneas de cada venta.
CREATE TABLE IF NOT EXISTS public.ventas_pos_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id        bigint  NOT NULL REFERENCES public.ventas_pos(id) ON DELETE CASCADE,
    origen          text    NOT NULL CHECK (origen IN ('stock', 'libre')),
    producto_id     bigint,       -- productos.id (stock) o productos_venta_libre.id (libre)
    nombre          text    NOT NULL,
    precio_unitario numeric NOT NULL DEFAULT 0,
    cantidad        numeric NOT NULL DEFAULT 1 CHECK (cantidad > 0),
    subtotal        numeric NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_ventas_pos_items_venta ON public.ventas_pos_items(venta_id);

-- Cierres de caja (una foto del día cuando la vendedora cierra).
CREATE TABLE IF NOT EXISTS public.cierres_caja (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       bigint  NOT NULL,
    vendedor_usuario text,
    fecha            date    NOT NULL,
    desde            timestamptz NOT NULL,
    hasta            timestamptz NOT NULL,
    total_ventas     numeric NOT NULL DEFAULT 0,
    cantidad_ventas  integer NOT NULL DEFAULT 0,
    total_efectivo   numeric NOT NULL DEFAULT 0,
    total_otros      numeric NOT NULL DEFAULT 0,
    detalle_json     jsonb,
    creado_en        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_cierres_caja_empresa_fecha ON public.cierres_caja(empresa_id, fecha);

-- RLS activado en todas, SIN políticas: nadie entra directo. El acceso es solo vía funciones
